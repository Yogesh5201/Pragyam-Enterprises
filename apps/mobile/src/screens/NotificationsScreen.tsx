export function NotificationsScreen() {
  const { language } = useMobileAuth();
  const [notifications, setNotifications] = useState<MobileNotification[]>(INITIAL_NOTIFICATIONS);
  const [activeFilter, setActiveFilter] = useState<'ALL' | 'UNREAD' | 'ORDERS'>('ALL');

  const unreadCount = notifications.filter(n => !n.read).length;

  const markAllAsRead = () => {
    setNotifications(prev => prev.map(n => ({ ...n, read: true })));
    Alert.alert(
      language === 'hi' ? 'सफलता' : 'Success',
      language === 'hi' ? 'सभी सूचनाएं पढ़ी हुई चिह्नित की गईं।' : 'All notifications marked as read.'
    );
  };

  const markOneAsRead = (id: string) => {
    setNotifications(prev =>
      prev.map(n => (n.id === id ? { ...n, read: true } : n))
    );
  };

  const filteredNotifs = notifications.filter(n => {
    if (activeFilter === 'UNREAD') return !n.read;
    if (activeFilter === 'ORDERS') return n.type === 'ORDER' || n.type === 'DISPATCH';
    return true;
  });

  const getIcon = (type: string) => {
    switch (type) {
      case 'DISPATCH': return '🚚';
      case 'PAYMENT': return '💰';
      case 'DEAL': return '🤝';
      case 'MATCH': return '✨';
      default: return '📦';
    }
  };

  return (
    <View style={styles.container}>
      {/* Top Banner */}
      <View style={styles.topHeader}>
        <View>
          <Text style={styles.headerTitle}>
            {language === 'hi' ? 'सूचना केंद्र' : 'Live Trade Alerts'}
          </Text>
          <Text style={styles.headerSubtitle}>
            {language === 'hi'
              ? `${unreadCount} नई सूचनाएं उपलब्ध हैं`
              : `${unreadCount} unread trade notifications`}
          </Text>
        </View>

        {unreadCount > 0 && (
          <TouchableOpacity onPress={markAllAsRead} style={styles.markAllBtn}>
            <Text style={styles.markAllText}>
              {language === 'hi' ? 'सभी पढ़ें' : 'Mark all read'}
            </Text>
          </TouchableOpacity>
        )}
      </View>

      {/* Filter Tabs */}
      <View style={styles.filterRow}>
        {(['ALL', 'UNREAD', 'ORDERS'] as const).map(tab => (
          <TouchableOpacity
            key={tab}
            onPress={() => setActiveFilter(tab)}
            style={[styles.filterChip, activeFilter === tab && styles.filterChipActive]}
          >
            <Text style={[styles.filterChipText, activeFilter === tab && styles.filterChipTextActive]}>
              {tab === 'ALL'
                ? language === 'hi' ? 'सभी' : 'All'
                : tab === 'UNREAD'
                ? language === 'hi' ? `अपठित (${unreadCount})` : `Unread (${unreadCount})`
                : language === 'hi' ? 'आदेश एवं डिस्पैच' : 'Orders & Dispatch'}
            </Text>
          </TouchableOpacity>
        ))}
      </View>

      {/* Notifications List */}
      <FlatList
        data={filteredNotifs}
        keyExtractor={item => item.id}
        contentContainerStyle={styles.listContent}
        renderItem={({ item }) => (
          <TouchableOpacity
            activeOpacity={0.8}
            onPress={() => markOneAsRead(item.id)}
            style={[styles.card, !item.read && styles.unreadCard]}
          >
            <View style={styles.cardHeader}>
              <View style={styles.typeBadge}>
                <Text style={styles.typeIcon}>{getIcon(item.type)}</Text>
                <Text style={styles.typeText}>{item.type}</Text>
              </View>
              <Text style={styles.timestamp}>{item.timestamp}</Text>
            </View>

            <Text style={styles.title}>
              {language === 'hi' ? item.titleHi : item.title}
            </Text>

            <Text style={styles.message}>
              {language === 'hi' ? item.messageHi : item.message}
            </Text>

            {item.referenceId && (
              <View style={styles.refRow}>
                <Text style={styles.refTag}>Ref: {item.referenceId}</Text>
                {!item.read && <View style={styles.blueDot} />}
              </View>
            )}
          </TouchableOpacity>
        )}
        ListEmptyComponent={
          <View style={styles.emptyBox}>
            <Text style={styles.emptyIcon}>🔔</Text>
            <Text style={styles.emptyText}>
              {language === 'hi' ? 'कोई नई सूचना नहीं है' : 'No notifications found'}
            </Text>
          </View>
        }
      />
    </View>
  );
}

